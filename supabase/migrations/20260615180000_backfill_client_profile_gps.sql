UPDATE public.client_profiles cp
SET
  latitude = lk.latitude,
  longitude = lk.longitude,
  updated_at = now()
FROM public._city_coord_lookup lk
WHERE cp.city IS NOT NULL
  AND trim(cp.city) <> ''
  AND (
    cp.latitude IS NULL
    OR cp.longitude IS NULL
    OR (abs(cp.latitude) < 0.0001 AND abs(cp.longitude) < 0.0001)
  )
  AND lower(trim(cp.city)) = lower(lk.city_name);

